from typing import List, Optional
from pydantic import BaseModel, Field


class IntakeInput(BaseModel):
    """Structured input payload received by the Product Intake Agent."""
    product_name: str = Field(description="Name of the course, kit, workbook, or digital product.")
    category: str = Field(description="E.g. Programming Courses, Robotics Kits, Arduino, Scratch, Digital Worksheets.")
    age_group: str = Field(description="Target age group, e.g., '8-12 years', 'Teens'.")
    difficulty: str = Field(description="Difficulty classification: Beginner, Intermediate, Advanced.")
    price: float = Field(description="Retail price of the product.")
    duration: Optional[str] = Field(default=None, description="Course duration, e.g. '12 hours', '4 weeks'.")
    language: str = Field(default="English", description="Instruction language.")
    tags: List[str] = Field(default_factory=list, description="Descriptive search labels.")
    learning_outcomes: List[str] = Field(default_factory=list, description="Core educational benefits.")
    prerequisites: List[str] = Field(default_factory=list, description="Required prior knowledge.")
    product_images: List[str] = Field(default_factory=list, description="Array of image urls or filenames to upload.")
    optional_notes: Optional[str] = Field(default=None, description="Additional context or formatting notes.")


class CanonicalProductContext(BaseModel):
    """The canonical product context generated by the Intake Agent to prepare for the platform workflow."""
    workflow_id: str = Field(description="Unique ID tracking the launch pipeline process.")
    product_id: str = Field(description="Unique catalog ID assigned to the product.")
    product_name: str = Field(description="Normalized title of the educational item.")
    category: str = Field(description="Validated product category classification.")
    price: float = Field(description="Base price value.")
    currency: str = Field(default="USD", description="Currency standard code.")
    age_group: str = Field(description="Target demographic age group.")
    difficulty: str = Field(description="Difficulty level.")
    duration: Optional[str] = Field(default=None, description="Course duration details.")
    language: str = Field(description="Course instruction language.")
    learning_outcomes: List[str] = Field(default_factory=list, description="Core educational objectives.")
    prerequisites: List[str] = Field(default_factory=list, description="Requirements list.")
    tags: List[str] = Field(default_factory=list, description="Standardized search label list.")
    uploaded_images: List[str] = Field(default_factory=list, description="Verified remote storage URLs.")
    status: str = Field(default="draft", description="Pipeline state status.")
    created_at: str = Field(description="ISO creation time.")
    updated_at: str = Field(description="ISO modification time.")


class IntakeResponse(BaseModel):
    """The structured JSON response returned by the Product Intake Agent."""
    status: str = Field(description="Result of execution: 'success' or 'failed'.")
    errors: List[str] = Field(default_factory=list, description="List of validation or processing error details.")
    canonical_context: Optional[CanonicalProductContext] = Field(default=None, description="The validated canonical product details.")
